class I18nService {
    public lang: Lang;

    constructor() {
        const saved = (typeof localStorage !== 'undefined') ? localStorage.getItem('infinitystock-lang') : null;
        this.lang = (saved === 'ko' || saved === 'en') ? saved : 'ko';
    }

    t(key: string): string {
        return dict[this.lang]?.[key] || dict['en']?.[key] || key;
    }

    setLang(lang: Lang) {
        this.lang = lang;
        if (typeof localStorage !== 'undefined') {
            localStorage.setItem('infinitystock-lang', lang);
        }
    }

    toggleLang() {
        this.setLang(this.lang === 'en' ? 'ko' : 'en');
    }

    get isKo(): boolean {
        return this.lang === 'ko';
    }
}

export const i18n = new I18nService();
